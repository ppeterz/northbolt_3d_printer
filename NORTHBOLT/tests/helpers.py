def make_gcode(path, layers=20, segs=30, tool=0, radius=15.0, m600_at=None):
    """A small sliced-looking print: start code, circles per layer, retracts, z-hops, end code."""
    import math
    out = [
        "; generated by NORTHBOLT tests (PrusaSlicer-like header)",
        "; thumbnail begin 1x1 92",
        "; " + PNG_1X1,
        "; thumbnail end",
        "M73 P0 R10",
        "M140 S60",
        f"M104 T{tool} S200",
        "M190 S60",
        f"M109 T{tool} S200",
        "G28 ; home all",
        "M420 S1",
    ]
    if tool == 1:
        out.append("T1")
    out += ["G90", "M82", "G92 E0", "G1 Z0.3 F600", "G1 X5 Y5 F3000", "G1 X60 Y5 E5 F1200 ; purge", "G92 E0"]
    e = 0.0
    cx, cy = 100.0, 137.0
    for layer in range(1, layers + 1):
        z = round(0.2 * layer, 3)
        out += [";LAYER_CHANGE", f";Z:{z}", f"G1 Z{z} F600", f"G1 X{cx + radius:.3f} Y{cy:.3f} F6000", "G1 E0.8 F2400" if layer > 1 else "G1 F1800"]
        if layer > 1:
            e += 0.8
            out[-1] = f"G1 E{e:.5f} F2400"
        if layer == 2:
            out.append("M106 S255")
        if m600_at == layer:
            out.append("M600")
        for i in range(1, segs + 1):
            a = 2 * math.pi * i / segs
            e += 0.06
            out.append(f"G1 X{cx + radius * math.cos(a):.3f} Y{cy + radius * math.sin(a):.3f} E{e:.5f} F1800")
        e -= 0.8
        out.append(f"G1 E{e:.5f} F2400")
        out.append(f"G1 Z{z + 0.4:.3f} F600")
        out.append(f"M73 P{int(100 * layer / layers)} R{max(0, layers - layer) // 2}")
    out += ["M104 T0 S0", "M104 T1 S0", "M140 S0", "M107", "G91", "G1 Z10 F600", "G90", "G28 X Y", "M84",
            "; estimated printing time (normal mode) = 1h 2m 3s", "; filament used [g] = 12.34"]
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    return out


def make_hex(blob, chunk=16):
    """Intel HEX for a byte string, with extended segment records past 64 KB (like avr-objcopy)."""
    lines = []
    seg = -1
    for off in range(0, len(blob), chunk):
        if off >> 16 != seg:
            seg = off >> 16
            rec = bytes([2, 0, 0, 2, (seg << 12) >> 8 & 0xFF, 0])
            lines.append(":" + (rec + bytes([-sum(rec) & 0xFF])).hex().upper())
        data = blob[off:off + chunk]
        addr = off & 0xFFFF
        rec = bytes([len(data), addr >> 8, addr & 0xFF, 0]) + data
        lines.append(":" + (rec + bytes([-sum(rec) & 0xFF])).hex().upper())
    lines.append(":00000001FF")
    return ("\n".join(lines) + "\n").encode()


def fake_firmware(name="Marlin 1.1.9.9 (Github)", size=70000):
    """A 'firmware image' that contains an M115 report string, like the real Marlin build."""
    text = f"FIRMWARE_NAME:{name} SOURCE_CODE_URL:https://github.com/MarlinFirmware/Marlin".encode()
    blob = bytearray(b"\x0c\x94" * (size // 2))
    blob[5000:5000 + len(text)] = text
    return make_hex(bytes(blob))


def file_commands(lines):
    from northbolt.gcode import clean, host_action
    cmds = []
    for line in lines:
        c = clean(line)
        if c and not host_action(c):
            cmds.append(c)
    return cmds


def venv_python():
    return sys.executable


def free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


class Rig:
    """Starts the simulator and the host, with HTTP and admin helpers."""

    def __init__(self, speed=25, error_rate=0.0, settings=None, env=None):
        self.env = env or {}
        self.sim_port = free_port()
        self.admin_port = free_port()
        self.http_port = free_port()
        self.data = tempfile.mkdtemp(prefix="northbolt-")
        self.speed = speed
        self.error_rate = error_rate
        if settings:
            with open(os.path.join(self.data, "settings.json"), "w") as fh:
                json.dump(settings, fh)
        self.sim = None
        self.host = None
        self.logs = []

    def start(self):
        self.sim = self._spawn([venv_python(), os.path.join(ROOT, "tools", "simulator.py"),
                                "--port", str(self.sim_port), "--admin", str(self.admin_port),
                                "--speed", str(self.speed), "--error-rate", str(self.error_rate)], "sim")
        self._wait_port(self.admin_port)
        self.start_host()
        return self

    def start_host(self):
        self.host = self._spawn([venv_python(), "-m", "northbolt", "--data", self.data,
                                 "--serial", f"socket://127.0.0.1:{self.sim_port}", "--port", str(self.http_port),
                                 "--host", "127.0.0.1"], "host")
        self._wait_port(self.http_port)
        self.wait(lambda s: s["connection"]["ready"], 30, "printer connection")

    def _spawn(self, args, name):
        log_path = os.path.join(self.data, f"{name}-{len(self.logs)}.log")
        fh = open(log_path, "w")
        self._files = getattr(self, "_files", []) + [fh]
        self.logs.append(log_path)
        return subprocess.Popen(args, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, env={**os.environ, **self.env})

    def _wait_port(self, port, timeout=20):
        end = time.time() + timeout
        while time.time() < end:
            try:
                socket.create_connection(("127.0.0.1", port), 0.5).close()
                return
            except OSError:
                time.sleep(0.1)
        raise RuntimeError(f"port {port} never opened; logs: {self.tail()}")

    def kill_host(self):
        self.host.kill()   # abrupt, like the Pi losing power
        self.host.wait()

    def stop(self):
        for p in (self.host, self.sim):
            if p and p.poll() is None:
                p.kill()
                p.wait()
        for fh in getattr(self, "_files", []):
            fh.close()
        time.sleep(0.2)
        shutil.rmtree(self.data, ignore_errors=True)

    def tail(self, n=40):
        out = []
        for path in self.logs:
            try:
                with open(path) as fh:
                    out.append(f"--- {os.path.basename(path)}\n" + "".join(fh.readlines()[-n:]))
            except OSError:
                pass
        return "\n".join(out)

    # ---------------------------------------------------------------- HTTP
    def api(self, method, path, data=None, expect_ok=True):
        req = urllib.request.Request(f"http://127.0.0.1:{self.http_port}{path}", method=method)
        payload = None
        if data is not None:
            payload = json.dumps(data).encode()
            req.add_header("Content-Type", "application/json")
        try:
            with urllib.request.urlopen(req, payload, timeout=30) as resp:
                return json.loads(resp.read() or b"{}")
        except urllib.error.HTTPError as exc:
            body = json.loads(exc.read() or b"{}")
            if expect_ok:
                raise AssertionError(f"{method} {path} -> {exc.code}: {body}")
            return {"status": exc.code, **body}

    def get(self, path):
        return self.api("GET", path)

    def post(self, path, data=None, expect_ok=True):
        return self.api("POST", path, data or {}, expect_ok)

    def state(self):
        return self.get("/api/state")

    def upload(self, path, name=None, url="/api/files", extra=None):
        boundary = "----northbolttest"
        name = name or os.path.basename(path)
        with open(path, "rb") as fh:
            content = fh.read()
        parts = [f"--{boundary}\r\nContent-Disposition: form-data; name=\"file\"; filename=\"{name}\"\r\n"
                 f"Content-Type: application/octet-stream\r\n\r\n".encode() + content + b"\r\n"]
        for k, v in (extra or {}).items():
            parts.append(f"--{boundary}\r\nContent-Disposition: form-data; name=\"{k}\"\r\n\r\n{v}\r\n".encode())
        body = b"".join(parts) + f"--{boundary}--\r\n".encode()
        req = urllib.request.Request(f"http://127.0.0.1:{self.http_port}{url}", data=body, method="POST")
        req.add_header("Content-Type", f"multipart/form-data; boundary={boundary}")
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.status, json.loads(resp.read())

    def wait(self, pred, timeout=60, what="condition", interval=0.1):
        end = time.time() + timeout
        last = None
        while time.time() < end:
            try:
                last = self.state()
                if pred(last):
                    return last
            except (urllib.error.URLError, ConnectionError, OSError):
                pass
            time.sleep(interval)
        raise AssertionError(f"Timed out waiting for {what}. Last job: {last and last.get('job')}\n{self.tail()}")

    # ---------------------------------------------------------------- simulator admin
    def admin(self, command):
        s = socket.create_connection(("127.0.0.1", self.admin_port), 5)
        s.sendall((command + "\n").encode())
        buf = b""
        while not buf.endswith(b"\n"):
            chunk = s.recv(65536)
            if not chunk:
                break
            buf += chunk
        s.close()
        return json.loads(buf)

    def sim_history(self, n=5000):
        return self.admin(f"history {n}")["history"]

    def wait_sim(self, pred, timeout=60, what="simulator condition"):
        end = time.time() + timeout
        while time.time() < end:
            last = self.admin("state")
            if pred(last):
                return last
            time.sleep(0.02)
        raise AssertionError(f"Timed out waiting for {what}. Host job: {self.state().get('job')}\n{self.tail()}")
